/// Fix/output mode for `wincheck` file inspection.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, Default, Display, IsVariant)]
pub enum WinCheckFixMode {
    /// Standard lint run formatting diagnostics via `--format`.
    #[default]
    #[display("report")]
    ReportOnly,
    /// Preview unified diff generated by `CstRewriter` (`--diff`).
    #[display("diff")]
    ShowDiff,
    /// Emit CST-rewritten script onto `stdout` for a single file or `"-"` (`--fix` / `--stdout`).
    #[display("fix")]
    ApplyFix,
    /// Write CST-rewritten scripts back to disk in place preserving original BOM & encoding (`--in-place`).
    #[display("fix_in_place")]
    ApplyFixInPlace,
}

/// Action parsed from `wincheck` CLI arguments.
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum WinCheckAction {
    /// Lint one or more script files (or `"-"` for standard input).
    LintFiles {
        /// File paths to lint.
        files: Vec<String>,
        /// Output format (`tty`, `json`, `sarif`, `gcc`).
        format: OutputFormat,
        /// Linter filter configuration (including `exec_context`).
        config: LinterConfig,
        /// Whether to report diagnostics, preview `--diff`, or emit `--fix`.
        fix_mode: WinCheckFixMode,
    },
    /// Explain a specific rule code (`--explain CMD2001`).
    ExplainRule(String),
    /// List all available lint rules (`--list-rules`).
    ListRules,
    /// Show CLI usage help (`--help`).
    ShowHelp,
    /// Show version (`--version`).
    ShowVersion,
}

/// Parses `wincheck` command-line arguments into a [`WinCheckAction`].
///
/// # Arguments
/// * `args` - Command-line arguments (excluding `argv[0]`).
///
/// # Returns
/// `Ok(WinCheckAction)` if valid.
///
/// # Errors
/// Returns [`CmdError::CliUsage`] if arguments are invalid or missing.
pub fn parse_wincheck_args(args: &[String]) -> Result<WinCheckAction, CmdError> {
    if args.is_empty() {
        return Ok(WinCheckAction::ShowHelp);
    }

    let mut format = OutputFormat::Tty;
    let mut config = LinterConfig::default();
    let mut fix_mode = WinCheckFixMode::ReportOnly;
    let mut files = Vec::new();
    let mut i = 0usize;

    while let Some(arg) = args.get(i) {
        match arg.as_str() {
            "-h" | "--help" | "/?" => return Ok(WinCheckAction::ShowHelp),
            "-V" | "--version" => return Ok(WinCheckAction::ShowVersion),
            "--list-rules" => return Ok(WinCheckAction::ListRules),
            "--diff" => fix_mode = WinCheckFixMode::ShowDiff,
            "--stdout" => fix_mode = WinCheckFixMode::ApplyFix,
            "--fix" => {
                if fix_mode != WinCheckFixMode::ApplyFixInPlace {
                    fix_mode = WinCheckFixMode::ApplyFix;
                }
            }
            "--in-place" => fix_mode = WinCheckFixMode::ApplyFixInPlace,
            "--unsafe-fixes" => {
                config.fix_safety = crate::linter::FixApplicability::UnsafeOptIn;
            }
            "--encoding" => {
                let enc_str = next_required_cli_value(args, i, arg)?;
                config.codepage = parse_wincheck_encoding_str(enc_str)?;
                i = i.saturating_add(2);
                continue;
            }
            "-m" | "--mode" => {
                let mode_str = next_required_cli_value(args, i, arg)?;
                config.exec_context = parse_wincheck_mode_str(mode_str)?;
                i = i.saturating_add(2);
                continue;
            }
            "--dialect" => {
                let dial_str = next_required_cli_value(args, i, arg)?;
                config.dialect = parse_wincheck_dialect_str(dial_str)?;
                i = i.saturating_add(2);
                continue;
            }
            "--explain" => {
                let code = next_required_cli_value(args, i, arg)?;
                return Ok(WinCheckAction::ExplainRule(code.to_owned()));
            }
            "-f" | "--format" => {
                let fmt_str = next_required_cli_value(args, i, arg)?;
                format = parse_wincheck_format_str(fmt_str)?;
                i = i.saturating_add(2);
                continue;
            }
            "-S" | "--severity" => {
                let sev_str = next_required_cli_value(args, i, arg)?;
                config.min_severity = parse_wincheck_severity_str(sev_str)?;
                i = i.saturating_add(2);
                continue;
            }
            "-e" | "--exclude" => {
                let list = next_required_cli_value(args, i, arg)?;
                insert_comma_rule_ids(list, &mut config.excluded_rules);
                i = i.saturating_add(2);
                continue;
            }
            "-i" | "--include" => {
                let list = next_required_cli_value(args, i, arg)?;
                insert_comma_rule_ids(list, &mut config.included_rules);
                i = i.saturating_add(2);
                continue;
            }
            _ if arg.starts_with("--encoding=") => {
                let enc_str = arg.get("--encoding=".len()..).unwrap_or("");
                config.codepage = parse_wincheck_encoding_str(enc_str)?;
            }
            _ if arg.starts_with("--dialect=") => {
                let dial_str = arg.get("--dialect=".len()..).unwrap_or("");
                config.dialect = parse_wincheck_dialect_str(dial_str)?;
            }
            _ if arg.starts_with('-') && arg != "-" => {
                return Err(CmdError::from(CliUsageFailure::new(
                    CliTool::WinCheck,
                    arg,
                    CliErrorReason::UnknownFlag,
                )));
            }
            _ => files.push(arg.clone()),
        }
        i = i.saturating_add(1);
    }

    validate_wincheck_files_and_fix_mode(&files, fix_mode)?;

    Ok(WinCheckAction::LintFiles {
        files,
        format,
        config,
        fix_mode,
    })
}

/// Callback type writing rewritten raw bytes to a target file path (`--in-place`).
type FileWriterFn<'a> = dyn FnMut(&str, &[u8]) -> Result<(), CmdError> + 'a;

/// Validates `files` and `fix_mode` combinations (`MissingInputFiles`, `MultiFileStdoutFixRequiresInPlace`,
/// and `InPlaceCannotUseStdin`).
///
/// # Arguments
/// * `files` - Parsed input file list.
/// * `fix_mode` - Selected [`WinCheckFixMode`].
///
/// # Returns
/// `Ok(())` when valid.
///
/// # Errors
/// Returns [`CmdError::CliUsage`] on invalid combinations.
fn validate_wincheck_files_and_fix_mode(
    files: &[String],
    fix_mode: WinCheckFixMode,
) -> Result<(), CmdError> {
    if files.is_empty() {
        return Err(CmdError::from(CliUsageFailure::new(
            CliTool::WinCheck,
            "<FILES...>",
            CliErrorReason::MissingInputFiles,
        )));
    }
    if fix_mode == WinCheckFixMode::ApplyFix && files.len() > 1 {
        return Err(CmdError::from(CliUsageFailure::new(
            CliTool::WinCheck,
            "--fix",
            CliErrorReason::MultiFileStdoutFixRequiresInPlace,
        )));
    }
    if fix_mode == WinCheckFixMode::ApplyFixInPlace && files.iter().any(|f| f == "-") {
        return Err(CmdError::from(CliUsageFailure::new(
            CliTool::WinCheck,
            "--in-place",
            CliErrorReason::InPlaceCannotUseStdin,
        )));
    }
    Ok(())
}

/// Parses a `wincheck --encoding` argument string into [`CodePage`].
///
/// # Arguments
/// * `enc_str` - Encoding name or codepage number (`"utf-8"`, `"cp437"`, `"cp850"`, `"cp1252"`, `"utf-16le"`, `"utf-16be"`).
///
/// # Returns
/// `Ok(CodePage)` if recognized.
///
/// # Errors
/// Returns [`CmdError::CliUsage`] on unsupported encoding strings.
fn parse_wincheck_encoding_str(enc_str: &str) -> Result<CodePage, CmdError> {
    match enc_str.trim().to_ascii_lowercase().as_str() {
        "utf8" | "utf-8" | "65001" => Ok(CodePage::Utf8),
        "ascii" | "20127" => Ok(CodePage::Ascii),
        "cp437" | "437" | "oem" => Ok(CodePage::OemUnitedStates),
        "cp850" | "850" => Ok(CodePage::OemMultilingualLatin1),
        "cp852" | "852" => Ok(CodePage::OemLatin2),
        "cp865" | "865" => Ok(CodePage::OemNordic),
        "cp866" | "866" => Ok(CodePage::OemCyrillic),
        "cp1252" | "1252" | "windows-1252" => Ok(CodePage::WindowsLatin1),
        "utf16" | "utf16le" | "utf-16" | "utf-16le" | "1200" => Ok(CodePage::Utf16Le),
        "utf16be" | "utf-16be" | "1201" => Ok(CodePage::Utf16Be),
        _ => Err(CmdError::from(CliUsageFailure::new(
            CliTool::WinCheck,
            "--encoding",
            CliErrorReason::InvalidEncodingValue(enc_str.to_owned()),
        ))),
    }
}

/// Parses a `wincheck --dialect` argument string into [`crate::types::ShellDialect`].
///
/// # Arguments
/// * `dial_str` - Dialect identifier (`"cmd"`, `"dos622"`, `"freedos"`).
///
/// # Returns
